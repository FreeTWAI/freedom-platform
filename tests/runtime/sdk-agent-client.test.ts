test('generated sdk agent-operations table matches granted allowlist operations', async () => {
  const modPath = new URL('../../packages/sdk/agent-operations.mjs', import.meta.url);
  assert.ok(readFileSync(modPath, 'utf8').startsWith('// Generated by scripts/build-agent-contract.mjs. Do not edit.\n'));
  const { agentOperations: sdkOperations } = (await import(modPath.href)) as { agentOperations: AgentOperation[] };
  const granted = allowlistOperations.filter((op) => op.granted !== false);
  assert.equal(sdkOperations.length, granted.length);
  const ids = new Set<string>();
  for (const op of sdkOperations) {
    assert.equal(typeof op.id, 'string');
    assert.ok(op.id.length > 0);
    assert.equal(ids.has(op.id), false);
    ids.add(op.id);
    assert.equal(typeof op.method, 'string');
    assert.equal(typeof op.path, 'string');
    assert.equal(op.path.startsWith('/api/v1'), false);
    assert.equal(op.path.includes('/:'), false);
    assert.equal(typeof op.scope, 'string');
    assert.equal(typeof op.if_match, 'boolean');
    const source = granted.find((g) => g.id === op.id);
    assert.ok(source, op.id);
    assert.equal(op.if_match, Boolean(source.ifMatch));
  }
});

test('createAgentClient validates baseUrl and token', () => {
  assert.throws(() => createAgentClient({ baseUrl: 'http://example.com/api/v1', token: validToken }), TypeError);
  assert.throws(() => createAgentClient({ baseUrl: 'https://example.com', token: validToken }), TypeError);
  assert.throws(() => createAgentClient({ baseUrl: 'https://example.com/api/v1/', token: validToken }), TypeError);
  assert.throws(() => createAgentClient({ baseUrl: 'https://example.com/api/v1', token: 'bad_token' }), TypeError);
  assert.throws(() => createAgentClient({ baseUrl: 'https://example.com/api/v1', token: `fw_agent_${'a'.repeat(42)}` }), TypeError);
  for (const baseUrl of [
    'https://freetwai.com/api/v1',
    'http://localhost:4310/api/v1',
    'http://127.0.0.1:4310/api/v1',
    'http://[::1]:4310/api/v1',
  ]) {
    const client = createAgentClient({ baseUrl, token: validToken, fetcher: async () => new Response('{}', { status: 200 }) });
    assert.ok(client.operations.length > 0);
  }
});

test('call sends bearer without cookie, omits credentials, encodes params and query, and honors headers', async () => {
  const seen: Array<{ url: string; init: RequestInit }> = [];
  const client = createAgentClient({
    baseUrl: 'https://freetwai.com/api/v1',
    token: validToken,
    fetcher: async (url, init = {}) => {
      seen.push({ url: String(url), init });
      return new Response(JSON.stringify({ ok: true }), { status: 200 });
    },
  });

  await client.call('tools.identity', {
    params: { guild: 'a/b', tool: 'my tool' },
    query: { cursor: 'c1', skipped: undefined },
    idempotencyKey: 'idem-key-1234',
  });
  assert.equal(seen[0].url, 'https://freetwai.com/api/v1/guilds/a%2Fb/tools/my%20tool/token?cursor=c1');
  assert.equal(seen[0].init.method, 'POST');
  assert.equal(seen[0].init.credentials, 'omit');
  assert.equal(seen[0].init.redirect, 'error');
  const h0 = seen[0].init.headers as Record<string, string>;
  assert.equal(h0.Authorization, `Bearer ${validToken}`);
  assert.equal(h0.Accept, 'application/json');
  assert.equal(h0.Cookie, undefined);
  assert.equal(h0.cookie, undefined);
  assert.equal(h0['Content-Type'], undefined);
  assert.equal(h0['Idempotency-Key'], 'idem-key-1234');

  await assert.rejects(() => client.call('unknown.op'), TypeError);
  await assert.rejects(() => client.call('tools.identity', { params: { guild: 'g1' } }), TypeError);
  await assert.rejects(() => client.call('events.update', { params: { id: 'e1' }, body: { title: 't' } }), TypeError);

  await client.call('events.update', {
    params: { id: 'e1' },
    body: { title: 't' },
    ifMatch: '"3"',
    idempotencyKey: 'idem-key-5678',
  });
  const h1 = seen[1].init.headers as Record<string, string>;
  assert.equal(h1['Content-Type'], 'application/json');
  assert.equal(h1['If-Match'], '"3"');
  assert.equal(h1['Idempotency-Key'], 'idem-key-5678');
  assert.equal(seen[1].init.body, '{"title":"t"}');

  // The change feed's query schema is strict on `after` (apps/platform-api/src/agent-schemas.ts).
  await client.events({ after: 'cur_1' });
  assert.equal(seen[2].url, 'https://freetwai.com/api/v1/agent/events?after=cur_1');
  await client.events({ after: undefined });
  assert.equal(seen[3].url, 'https://freetwai.com/api/v1/agent/events');
});

test('call handles 204, AgentError codes, and timeout abort', async () => {
  let mode: 'no-content' | 'code' | 'error' | 'bare' | 'hang' = 'no-content';
  const client = createAgentClient({
    baseUrl: 'https://freetwai.com/api/v1',
    token: validToken,
    timeoutMs: 25,
    fetcher: (_url, init) => {
      if (mode === 'no-content') return Promise.resolve(new Response(null, { status: 204 }));
      if (mode === 'code') return Promise.resolve(new Response(JSON.stringify({ code: 'rate_limited', error: 'ignored' }), { status: 429 }));
      if (mode === 'error') return Promise.resolve(new Response(JSON.stringify({ error: 'stale_version' }), { status: 412 }));
      if (mode === 'bare') return Promise.resolve(new Response('bad gateway', { status: 502 }));
      return new Promise((_, reject) => {
        init?.signal?.addEventListener('abort', () => reject(init.signal?.reason ?? new Error('aborted')));
      });
    },
  });

  assert.equal(await client.call('guilds.list'), null);

  mode = 'code';
  await assert.rejects(
    () => client.call('guilds.list'),
    (err: unknown) => err instanceof AgentError && err.status === 429 && err.code === 'rate_limited',
  );

  mode = 'error';
  await assert.rejects(
    () => client.call('guilds.list'),
    (err: unknown) => err instanceof AgentError && err.status === 412 && err.code === 'stale_version',
  );

  mode = 'bare';
  await assert.rejects(
    () => client.call('guilds.list'),
    (err: unknown) => err instanceof AgentError && err.status === 502 && err.code === 'http_502',
  );

  mode = 'hang';
  await assert.rejects(() => client.call('guilds.list'));
});

test('real fw_agent_ token works against platform-api over createAgentClient', async () => {
  const login = await fetch(`${origin}/api/v1/auth/login`, {
    method: 'POST',
    headers: { Origin: origin, 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: DEMO_USERS[0].email, password: DEMO_PASSWORD }),
  });
  assert.equal(login.status, 200);
  const loginData = (await login.json()) as { csrf_token: string; user: { user_id: string } };
  await pool.query('UPDATE users SET onboarding_completed_at=now() WHERE user_id=$1', [loginData.user.user_id]);
  const cookie = login.headers.get('set-cookie')!.split(';')[0];

  const issuedRes = await fetch(`${origin}/api/v1/me/agent-tokens`, {
    method: 'POST',
    headers: {
      Origin: origin,
      Cookie: cookie,
      'X-CSRF-Token': loginData.csrf_token,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ name: 'SDK Test Agent', scopes: ['read'] }),
  });
  assert.equal(issuedRes.status, 201);
  const issued = (await issuedRes.json()) as { access_token: string };
  assert.match(issued.access_token, /^fw_agent_[A-Za-z0-9_-]{43}$/);

  const client = createAgentClient({
    baseUrl: `${origin}/api/v1`,
    token: issued.access_token,
  });

  const guilds = (await client.call('guilds.list')) as { items: Array<{ guild_key: string }> };
  assert.equal(Array.isArray(guilds.items), true);
  assert.ok(guilds.items.length > 0);
  assert.equal(typeof guilds.items[0].guild_key, 'string');

  const feed = (await client.events()) as { items: unknown[]; next_cursor: string };
  assert.equal(Array.isArray(feed.items), true);
  assert.equal(typeof feed.next_cursor, 'string');
});

