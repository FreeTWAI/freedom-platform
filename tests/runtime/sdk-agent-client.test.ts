  assert.equal(seen[0].init.method, 'POST');
  assert.equal(seen[0].init.credentials, 'omit');
  assert.equal(seen[0].init.redirect, 'error');
  const h0 = seen[0].init.headers as Record<string, string>;
  assert.equal(h0.Authorization, `Bearer ${validToken}`);
  assert.equal(h0.Accept, 'application/json');
  assert.equal(h0.Cookie, undefined);
  assert.equal(h0.cookie, undefined);
  assert.equal(h0['Content-Type'], undefined);
  assert.equal(h0['Idempotency-Key'], 'idem-key-1234');

  await assert.rejects(() => client.call('unknown.op'), TypeError);
  await assert.rejects(() => client.call('tools.identity', { params: { guild: 'g1' } }), TypeError);
  await assert.rejects(() => client.call('events.update', { params: { id: 'e1' }, body: { title: 't' } }), TypeError);

