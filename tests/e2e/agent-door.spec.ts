import {randomUUID} from 'node:crypto';
import {test,expect} from './fixtures.js';
import {openFeatureSearch} from './navigation.js';
import {e2eOrigin} from '../../packages/testing/e2e-origin.js';
// The ephemeral credential must not be captured in Playwright traces/screenshots.
test.use({trace:'off',screenshot:'off'});
test('member creates one token in the portal; their agent registers and reads its own change feed',async({page,e2eAuthPool},testInfo)=>{
 const id=randomUUID(),origin=e2eOrigin();
 await e2eAuthPool.query(`INSERT INTO community_events(event_id,community_id,organizer_ref,title,description,starts_at,ends_at,mode,location,state,visibility,event_kind)
 SELECT $1,community_id,user_id,'Agent 報名測試','合成活動',now()+interval '1 day',now()+interval '25 hours','online','線上','published','open','other' FROM users WHERE email='maker@local.test'`,[id]);
 await page.goto('/');
 await page.getByLabel('電子郵件',{exact:true}).fill('maker@local.test');
 await page.getByLabel('密碼',{exact:true}).fill('freedom-local-demo');
 await page.getByRole('button',{name:'登入',exact:true}).click();
 await expect(page.locator('.shell')).toBeVisible();
 await openFeatureSearch(page);
 await page.getByRole('navigation',{name:'主要工作區'}).getByRole('button',{name:'自動化',exact:true}).click();
 await expect(page).toHaveURL(/#automation\/agent$/);
 await expect(page.getByLabel('自動化檢視')).toHaveValue('#automation/agent');
 const panel=page.getByRole('region',{name:'Agent 連線'});
 await panel.getByRole('button',{name:'建立金鑰',exact:true}).click();
 const block=panel.getByLabel('交給 Agent（僅此一次）');await expect(block).toBeVisible();
 const text=await block.inputValue(),match=/fw_agent_[A-Za-z0-9_-]{43}/.exec(text);
 expect(Boolean(match),'one-time block contains the newly issued credential').toBe(true);
 const token=match![0];
 await panel.getByRole('button',{name:'已保存',exact:true}).click();await expect(block).toHaveCount(0);
 const registration=await fetch(`${origin}/api/v1/events/${id}/rsvp`,{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json','Idempotency-Key':randomUUID()},body:JSON.stringify({going:true})});
 expect(registration.status).toBe(200);
 const event=await registration.json() as {my_rsvp:string};expect(event.my_rsvp).toBe('going');
 const feed=await fetch(origin+'/api/v1/agent/events',{headers:{Authorization:'Bearer '+token}});
 expect(feed.status).toBe(200);const changes=await feed.json() as {items:{kind:string;resource_id:string}[]};
 expect(changes.items.some(item=>item.kind==='rsvp.confirmed'&&item.resource_id===id)).toBe(true);
 await panel.getByRole('button',{name:'更新連線'}).click();
 await panel.locator('summary').filter({hasText:'我的 Agent'}).click();
 await expect(panel.getByText(/最近使用：/)).not.toContainText('尚未使用');
 const publishKey=randomUUID(),body={title:'Agent 發布測試',description:'等待本人確認',starts_at:new Date(Date.now()+86400000).toISOString(),ends_at:new Date(Date.now()+90000000).toISOString(),mode:'online',location:'線上',capacity:20,visibility:'open'};
 const publish=()=>fetch(origin+'/api/v1/events',{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json','Idempotency-Key':publishKey},body:JSON.stringify(body)});
 expect((await publish()).status).toBe(202);
 await panel.getByRole('button',{name:'更新連線'}).click();
 await expect(panel.getByRole('button',{name:'確認公開此內容'})).toBeVisible();
 await panel.getByRole('button',{name:'確認公開此內容'}).click();
 await expect(panel.getByText('已確認，請 Agent 重試')).toBeVisible();
 expect((await publish()).status).toBe(201);
 await panel.getByRole('button',{name:'更新連線'}).click();
 await expect(panel.getByText('首次公開',{exact:true})).toHaveCount(0);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await panel.screenshot({path:testInfo.outputPath('agent-tokens-390.png')});
 await page.reload();await expect(page.getByLabel('自動化檢視')).toHaveValue('#automation/agent');
 await expect(page.getByLabel('交給 Agent（僅此一次）')).toHaveCount(0);
 await page.getByRole('region',{name:'Agent 連線'}).locator('summary').filter({hasText:'我的 Agent'}).click();
 await page.getByRole('button',{name:'撤銷',exact:true}).click();
 await expect(page.getByRole('region',{name:'Agent 連線'}).locator('summary').filter({hasText:'我的 Agent'})).toContainText('已撤銷');
 expect((await fetch(origin+'/api/v1/agent/events',{headers:{Authorization:'Bearer '+token}})).status).toBe(401);
});
