import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {agentOperations} from '../apps/platform-api/src/agent-allowlist.ts';
import {tsImport} from 'tsx/esm/api';
const {agentBodySchemas,agentPathSchemas,agentQuerySchemas,agentResponseSchemas,agentPendingSchema,agentErrorSchema,agentInputSchema,agentJsonSchema}=await tsImport('../apps/platform-api/src/agent-schemas.ts',import.meta.url);
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const active=agentOperations.filter(op=>op.granted!==false);
const created=new Set(['events.share','repositories.share','posts.note','posts.link','posts.comment','services.create','works.create','skills.draft']);
const pendingJson=agentJsonSchema(agentPendingSchema);
const errorContent={content:{'application/json':{schema:agentJsonSchema(agentErrorSchema)}}};
const paths={},sdkOperations=[];
for(const op of active){
 const path=op.route.replace('/api/v1','').replace(/:([a-z_]+)/g,'{$1}');
 sdkOperations.push({id:op.id,method:op.method,path,scope:op.scope,if_match:Boolean(op.ifMatch)});
 const parameters=[...path.matchAll(/\{([^}]+)\}/g)].map(m=>({name:m[1],in:'path',required:true,schema:agentJsonSchema(agentPathSchemas[m[1]])}));
 if(op.method!=='GET')parameters.push({name:'Idempotency-Key',in:'header',required:true,schema:{type:'string',pattern:'^[A-Za-z0-9_-]{8,128}$'}});
 if(op.ifMatch)parameters.push({name:'If-Match',in:'header',required:true,description:'最新活動 aggregate_version，含雙引號。',schema:{type:'string'}});
 if(agentQuerySchemas[op.id])for(const [name,schema] of Object.entries(agentQuerySchemas[op.id].shape))parameters.push({name,in:'query',required:false,schema:agentJsonSchema(schema)});
 const success=created.has(op.id)?'201':'200';
 const successDesc=success==='201'?'已建立，實際發布狀態依回應 state。':'操作成功；欄位沿用原會員 API。';
 const responseSchema=agentResponseSchemas[op.id];
 const successContent=responseSchema?{content:{'application/json':{schema:agentJsonSchema(responseSchema)}}}:{};
 paths[path]??={};paths[path][op.method.toLowerCase()]={operationId:op.id,summary:op.title,'x-required-scope':op.scope,
 ...(op.featureFlag?{'x-feature-flag':op.featureFlag}:{}),
 security:[{AgentBearer:[]}],parameters,
 'x-input-schema':agentJsonSchema(agentInputSchema(op)),
 'x-body-schema':agentJsonSchema(agentBodySchemas[op.id]),
 ...(op.method!=='GET'?{requestBody:{required:true,content:{'application/json':{schema:agentJsonSchema(agentBodySchemas[op.id]),...(op.example?{example:op.example}:{})}}}}:{}),
 responses:{
  [success]:{description:successDesc,...successContent},
  ...(op.publicItem?{'202':{description:'pending_member：請會員確認後以相同內容和 key 重試。',content:{'application/json':{schema:pendingJson}}}}:{}),
  '401':{description:'金鑰到期、撤銷或停用。',...errorContent},
  '403':{description:'權限不足或功能未開放。',...errorContent},
  '409':{description:'內容或狀態衝突，停止並詢問會員。',...errorContent},
  '429':{description:'已達限制，停止操作。',...errorContent},
 }};
}
const contract={'x-denied-operations':agentOperations.filter(op=>op.granted===false).map(({method,route,title,featureFlag})=>({method,route,title,...(featureFlag?{featureFlag}:{}),agent_scope:null})),openapi:'3.1.1',info:{title:'自由工坊 Agent API',version:'1.0.0',description:'由 agent-allowlist.ts 產生；未列入的操作一律拒絕。'},servers:[{url:'https://freetwai.com/api/v1'}],components:{securitySchemes:{AgentBearer:{type:'http',scheme:'bearer',bearerFormat:'fw_agent_opaque'}}},paths};
const outputs={
 'contracts/agent/v1/openapi.json':JSON.stringify(contract,null,2)+'\n',
 'apps/portal-web/src/modules/agent-operations.ts':'// Generated by scripts/build-agent-contract.mjs. Do not edit.\nexport const agentOperations = '+JSON.stringify(active,null,2)+' as const;\n',
 'modules/client-connections/agent-contract.ts':'// Generated by scripts/build-agent-contract.mjs. Do not edit.\nexport const agentContract = '+JSON.stringify(contract,null,2)+';\n',
 'packages/sdk/agent-operations.mjs':'// Generated by scripts/build-agent-contract.mjs. Do not edit.\nexport const agentOperations = '+JSON.stringify(sdkOperations,null,2)+';\n',
};
let drift=false;
for(const [path,content] of Object.entries(outputs)){
 const file=resolve(root,path);
 if(process.argv.includes('--check')){let actual;try{actual=readFileSync(file,'utf8');}catch{}if(actual!==content){console.error('Agent contract differs: '+path);drift=true;}}
 else {mkdirSync(dirname(file),{recursive:true});writeFileSync(file,content);}
}
if(drift)process.exitCode=1;else console.log(`Agent contract: ${active.length} operations${process.argv.includes('--check')?' checked':' generated'}.`);
